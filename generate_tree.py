# generate_tree.py
import os
from pathlib import Path


def generate_tree(
        dir_path,
        prefix='',
        exclude_dirs={
            '.venv', 'venv', '__pycache__', '.git', 'node_modules',
            '.vscode', '.idea', '.pytest_cache', '.mypy_cache',
            '.coverage', 'htmlcov', 'logs', '__pycache__', '.pytest_cache'
        },
        stop_at={'staticfiles', 'fontawesome', 'webfonts', 'migrations', '__pycache__'}
):
    """
    Generate directory tree as text.
    Shows stop_at folders and their immediate contents but doesn't go deeper.
    """
    result = []

    try:
        items = sorted(os.listdir(dir_path))
    except PermissionError:
        return result

    # Filter out excluded directories
    items = [item for item in items if item not in exclude_dirs]

    for i, item in enumerate(items):
        path = os.path.join(dir_path, item)
        is_last = (i == len(items) - 1)

        branch = '└── ' if is_last else '├── '
        extension = '    ' if is_last else '│   '

        # Skip certain files from detailed listing
        if item in ['project_directory.txt', 'generate_tree.py', 'tree_output.txt', 'project_directory_structure.md']:
            continue

        if os.path.isdir(path):
            result.append(f"{prefix}{branch}{item}/")

            # Stop recursion INSIDE certain folders - just show immediate children
            if item in stop_at:
                try:
                    sub_items = sorted(os.listdir(path))
                    # Limit sub-items to avoid huge output
                    max_sub_items = 50
                    sub_items_to_show = sub_items[:max_sub_items]

                    for j, sub in enumerate(sub_items_to_show):
                        sub_last = (j == len(sub_items_to_show) - 1)
                        sub_branch = '└── ' if sub_last else '├── '
                        sub_path = os.path.join(path, sub)

                        if os.path.isdir(sub_path):
                            result.append(f"{prefix}{extension}{sub_branch}{sub}/")
                        else:
                            result.append(f"{prefix}{extension}{sub_branch}{sub}")

                    if len(sub_items) > max_sub_items:
                        result.append(f"{prefix}{extension}└── ... and {len(sub_items) - max_sub_items} more files")
                except PermissionError:
                    pass
            else:
                # Continue recursion for other directories
                result.extend(
                    generate_tree(
                        path,
                        prefix + extension,
                        exclude_dirs,
                        stop_at
                    )
                )
        else:
            # Skip .pyc files
            if not item.endswith('.pyc'):
                result.append(f"{prefix}{branch}{item}")

    return result


def save_structure():
    project_root = Path(__file__).parent

    print("🔍 Scanning Caldan Construction project structure...")
    print(f"📂 Root: {project_root}")
    print()

    tree_lines = generate_tree(str(project_root))

    # Count files and folders
    total_files = 0
    total_folders = 0

    for line in tree_lines:
        line = line.rstrip()
        if line.endswith('/'):
            total_folders += 1
        else:
            # Only count actual files (not directory markers)
            if not line.endswith('/'):
                total_files += 1

    # Build the header
    header = []
    header.append('╔══════════════════════════════════════════════════════════════╗')
    header.append('║        CALDAN CONSTRUCTION - PROJECT STRUCTURE               ║')
    header.append('║        Building Kenya\'s Future, One Project at a Time       ║')
    header.append('║        Technical Specification: CAL-SPEC-2026-07-V1.0       ║')
    header.append('╚══════════════════════════════════════════════════════════════╝')
    header.append('')
    header.append(f'📁 Project Root: {project_root}')
    header.append(f'📄 Total Files: {total_files}')
    header.append(f'📁 Total Folders: {total_folders}')
    header.append(f'📅 Generated: {__import__("datetime").datetime.now().strftime("%B %d, %Y %H:%M:%S")}')
    header.append('=' * 70)
    header.append('')

    # Write to .txt file
    txt_path = project_root / 'project_directory.txt'
    with open(txt_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(header))
        f.write('\n'.join(tree_lines))
        f.write('\n\n')
        f.write('=' * 70 + '\n')
        f.write('END OF CALDAN CONSTRUCTION PROJECT STRUCTURE\n')
        f.write(f'Generated by generate_tree.py\n')
        f.write(f'Total Files: {total_files} | Total Folders: {total_folders}\n')
        f.write(f'Python Version: {os.sys.version}\n' if hasattr(os, 'sys') else '')

    # Print to terminal
    print('\n'.join(header))
    print('\n'.join(tree_lines))
    print()
    print('=' * 70)
    print(f'✅ Directory structure saved to: {txt_path}')
    print(f'📄 Total Files: {total_files}')
    print(f'📁 Total Folders: {total_folders}')
    print()
    print('💡 Tip: Run this script whenever you add new files/directories')
    print('   to keep your project documentation up to date.')


def generate_markdown_structure():
    """Generate Markdown version for README.md"""
    project_root = Path(__file__).parent

    tree_lines = generate_tree(str(project_root))

    md_lines = []
    md_lines.append('## 📁 Project Directory Structure')
    md_lines.append('')
    md_lines.append('```')
    md_lines.extend(tree_lines)
    md_lines.append('```')
    md_lines.append('')

    # Save markdown version
    md_path = project_root / 'project_directory_structure.md'
    with open(md_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(md_lines))

    print(f'✅ Markdown version saved to: {md_path}')


if __name__ == '__main__':
    save_structure()
    print()
    generate_markdown_structure()